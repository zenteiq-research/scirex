def _command_flags(command: str) -> dict:
    """``--name v1 v2`` pairs of a command line (``<dir>`` placeholders skipped)."""
    flags: dict = {}
    for part in command.split(" --")[1:]:
        name, *vals = part.split()
        if any(v.startswith("<") or v.startswith("/") for v in vals):
            continue
        nums = [
            float(v) if "." in v else int(v)
            for v in vals
            if v.lstrip("-").replace(".", "").isdigit()
        ]
        flags[name] = (
            True if not vals else (nums if len(nums) == len(vals) else " ".join(vals))
        )
        if isinstance(flags[name], list) and len(flags[name]) == 1:
            flags[name] = flags[name][0]
    return flags


def legacy_config(rep: dict, metrics: dict) -> tuple[dict, dict]:
    """Architecture and training of a checkpoint with no ``config.json``, from the
    arguments its ``REPRODUCE.json`` records and the ``metrics.json`` beside it."""
    args = dict(rep.get("script_arguments", {}))
    if not args and rep.get("command"):
        flags = _command_flags(rep["command"])
        arch = {k.replace("-", "_"): v for k, v in flags.items() if k in ARCH_FLAGS}
        train = {
            k.replace("-", "_"): v for k, v in flags.items() if k not in ARCH_FLAGS
        }
        return arch, train
    arch = {k: metrics[k] for k in ARCH_KEYS if k in metrics}
    arch.update({k: args[k] for k in ARCH_KEYS if k in args})
    train = {k: v for k, v in args.items() if k not in ARCH_KEYS}
    return arch, train


def _car_cfd_training(run: dict, tr: dict) -> dict:
    """Car-CFD's training line, from the run's own settings.

    Its ``training`` block starts from the GINO paper's protocol (learning rate 2.5e-4)
    for every model, so it names the wrong rate for Transolver and GIWO; the run block
    holds what the run used, including its schedule.
    """
    keys = ("learning_rate", "schedule", "lr_step", "lr_gamma", "weight_decay")
    keys += ("batch_size", "n_epochs", "n_train", "n_test")
    train = {k: run[k] if k in run else tr[k] for k in keys if k in run or k in tr}
    if train.get("schedule"):  # a one-cycle style schedule replaces the step decay
        train.pop("lr_step", None)
        train.pop("lr_gamma", None)
    else:
        train.pop("schedule", None)
    return train


def config_of(
    cfg: dict, rep: dict, metrics: dict | None = None, bench: str = ""
) -> tuple[str, str]:
    """(architecture, training) as one line each."""
    if cfg:
        run, tr = cfg.get("run", {}), cfg.get("training", {})
        arch = run.get("arch") or run.get("model") or {}
        if bench == "car_cfd":
            train = _car_cfd_training(run, tr)
        else:
            train = {
                k: tr[k] if k in tr else run[k]
                for k in TRAIN_KEYS
                if k in tr or k in run
            }
        train.update(run.get("opt", {}))
    else:
        arch, train = legacy_config(rep, metrics or {})
    if str(train.get("epochs", "")).startswith("0 (no"):  # a placeholder: that run
        train.pop("epochs")  # is counted in steps, so the line leaves epochs out
    arch = _fmt(arch) if isinstance(arch, dict) else str(arch)
    return arch or UNKNOWN, _fmt(train) or UNKNOWN


def count_params(weights: Path) -> int | None:
    """Real parameters in a weights file (a complex weight counts as two), the way
    ``config.json`` counts them; ``None`` if the file cannot be read."""
    try:
        import numpy as np
        from flax import serialization

        tree = serialization.msgpack_restore(weights.read_bytes())
    except Exception:
        return None
    total, stack = 0, [tree]
    while stack:
        node = stack.pop()
        if isinstance(node, dict):
            stack.extend(node.values())
        elif isinstance(node, (list, tuple)):
            stack.extend(node)
        elif hasattr(node, "shape"):
            total += int(np.prod(node.shape)) * (2 if np.iscomplexobj(node) else 1)
    return total


def params_of(d: Path, weights: list[str], recorded) -> str:
    """Counted from the weights; flags a recorded count that disagrees."""
    main = "params.msgpack" if "params.msgpack" in weights else (weights or [""])[0]
    n = count_params(d / main) if main else None
    if n is None:
        return str(recorded) if recorded else UNKNOWN
    if recorded and recorded != n:
        return f"{n} (the archive records {recorded})"
    return str(n)


def load_diff(path: Path | None) -> dict[tuple[str, str], dict]:
    if path is None or not path.is_file():
        return {}
    with open(path) as f:
        return {(r["row"], r["model"]): r for r in csv.DictReader(f)}


def _stale(created: str, diff_path: Path | None) -> bool:
    """True when the checkpoint is newer than the reproduce run that measured it."""
    if not created or diff_path is None or not diff_path.is_file():
        return False
    try:
        made = datetime.fromisoformat(created).timestamp()
    except ValueError:
        return False
    return made > diff_path.stat().st_mtime


def weights_hashes(inventory: Path = DEFAULT_INVENTORY) -> dict[str, str]:
    """Archive path (relative to the checkpoint root) -> SHA-256 of its weights file,
    from the checkpoint inventory that ``inventory_checkpoints.py`` writes."""
    if not inventory.is_file():
        return {}
    prefix = "Checkpoints_Benchmarks/"  # some rows carry it, some do not
    best: dict[str, tuple[str, str]] = {}  # key -> (created_utc, sha256)
    with open(inventory, newline="") as f:
        for r in csv.DictReader(f):
            if not r.get("weights_sha256"):
                continue
            key = r["path"].removeprefix(prefix)
            # a path may be listed twice (an older run and the one that replaced it):
            # keep the newest, so the hash belongs to the weights the card describes
            if key not in best or r.get("created_utc", "") >= best[key][0]:
                best[key] = (r.get("created_utc", ""), r["weights_sha256"])
    return {k: v[1] for k, v in best.items()}


def describe(root: Path, ckpt: str, diff_path: Path | None) -> dict:
    d = root / ckpt
    files = sorted(p.name for p in d.iterdir() if p.is_file())
    cfg, man, rep = (
        _json(d / n) for n in ("config.json", "MANIFEST.json", "REPRODUCE.json")
    )
    metrics = _json(d / "metrics.json")
    arch, train = config_of(cfg, rep, metrics, classify(Path(ckpt))[0])
    weights = [f for f in files if f.endswith(".msgpack")]
    recorded = cfg.get("n_params") or metrics.get("n_params_real")
    created = cfg.get("provenance", {}).get("created_utc") or man.get("copied", "")
    return {
        "path": ckpt,
        "weights": weights,
        "n_params": params_of(d, weights, recorded),
        "arch": arch,
        "train": train,
        "command": rep.get("command", ""),
        "seed": seed_of(cfg),
        "epoch_rule": epoch_rule(classify(Path(ckpt))[0], cfg, files),
        "commit": commit_of(cfg, man, rep),
        "created": created or UNKNOWN,
        "created_label": "Created"
        if cfg.get("provenance", {}).get("created_utc")
        else "Copied to archive",
        "stale": _stale(created, diff_path),
        "converted_from": cfg.get("provenance", {}).get("converted_from", ""),
        "recorded": {
            k: v
            for k, v in cfg.get("training", {}).items()
            if k.startswith(("final_test", "best_test"))
        },
    }


