def gather(
    bench: str,
    root: Path,
    diff: dict,
    diff_path: Path | None,
    hashes: dict[str, str] | None = None,
    describe_fn=None,
    experimental: bool = False,
) -> dict:
    """The facts of one benchmark: a row per paper cell, details per checkpoint.

    ``experimental`` selects the cells of the experimental models instead of the others.
    """
    describe_fn = describe_fn or describe
    hashes = weights_hashes() if hashes is None else hashes
    cells = [
        c
        for c in CELLS
        if c.ckpt
        and benchmark_of(c.ckpt) == bench
        and c.row not in SKIP_ROWS
        and (c.model in EXPERIMENTAL_MODELS) == experimental
    ]
    by_ckpt: dict[str, list] = {}
    for c in cells:
        by_ckpt.setdefault(c.ckpt, []).append(c)
    rows, details = [], []
    for ckpt, cs in by_ckpt.items():
        info = describe_fn(root, ckpt, diff_path)
        sha = hashes.get(ckpt, UNKNOWN)
        for c in cs:
            r = diff.get((c.row, c.model))
            if r is None:
                ours, result = "not run", "-"
            elif info["stale"]:
                ours, result = "stale", "-"
            else:
                ours = f"{float(r['ours']):.4g}" if r["ours"] else "-"
                result = r["status"]
            rows.append(
                {
                    "model": c.model,
                    "ckpt": ckpt,
                    "params": info["n_params"],
                    "seed": info["seed"],
                    "sha": sha,
                    "row": c.row,
                    "metric": c.metric,
                    "unit": c.unit,
                    "ours": ours,
                    "result": result,
                }
            )
        models = ", ".join(dict.fromkeys(c.model for c in cs))
        details.append({"models": models, "ckpt": ckpt, "sha": sha, **info})
    return {"bench": bench, "rows": rows, "details": details}


