def _params_text(n: str) -> str:
    return f"{int(n):,}" if str(n).isdigit() else str(n)


# Benchmarks whose checkpoints and data are not released: the card gives the results only,
# without checkpoint names, SHA-256 values or download links.
UNRELEASED = {"cavity"}


def _table(section: dict, hf_repo: str) -> list[str]:
    rows = section["rows"]
    released = section["bench"] not in UNRELEASED
    several = len({(r["row"], r["metric"]) for r in rows}) > 1
    # the unit goes in the label only when the rows do not share one
    with_unit = len({(r["metric"], r["unit"]) for r in rows}) > 1
    head = ["Model"] + (["Checkpoint"] if released else []) + ["Parameters"]
    head += ["SHA-256"] if released else []
    head += ["Metric"] if several else []
    head += ["Reproduced"]
    head += ["Download"] if hf_repo and released else []
    out = [
        "| " + " | ".join(head) + " |",
        "|" + "|".join("---" for _ in head) + "|",
    ]
    for i, r in enumerate(rows):
        sha = r["sha"] if r["sha"] == UNKNOWN else f"`{r['sha'][:12]}`"
        cells = [r["model"]]
        cells += [f"`{r['ckpt']}`"] if released else []
        cells += [_params_text(r["params"])]
        cells += [sha] if released else []
        if i and (r["ckpt"], r["model"]) == (rows[i - 1]["ckpt"], rows[i - 1]["model"]):
            cells = [""] * len(cells)  # a second cell of the same checkpoint
        cells += [_row_label(r, with_unit)] if several else []
        cells += [r["ours"]]
        if hf_repo and released:
            repo = hf_repo_of(r["model"], r["ckpt"], hf_repo)
            cells.append(
                f"[Hugging Face](https://huggingface.co/{repo})" if repo else "-"
            )
        out.append("| " + " | ".join(cells) + " |")
    return out


def _details(section: dict) -> list[str]:
    out = ['??? note "Configuration and training"', ""]
    for d in section["details"]:
        weights = ", ".join(f"`{w}`" for w in d["weights"]) or UNKNOWN
        bullets = [
            f"- Weights: {weights}",
            f"- SHA-256: {d['sha']}",
            f"- Architecture: {d['arch']}",
            f"- Training: {d['train']}",
        ]
        if not d["epoch_rule"].startswith(UNKNOWN):  # the commit, dates and the archive
            bullets.append(f"- Epoch rule: {d['epoch_rule']}")  # layout stay internal
        out += [f"    **{d['models']}**, `{d['ckpt']}`", ""]
        out += [f"    {b}" for b in bullets] + [""]
    return out[:-1]


def render(sections: list[dict], hf_repo: str = "", experimental: bool = False) -> str:
    """A Checkpoint Cards page from the gathered facts (or the experimental one)."""
    if experimental:
        intro = [
            "# Experimental Checkpoint Cards",
            "",
            GENERATED,
            "",
            "The checkpoints of the [experimental models](../experimental/index.md), "
            "in the same form as the [checkpoint cards](index.md): the parameters, the "
            "SHA-256 of the weights and the value `reproduce.py` gives from them "
            "(Reproduced).",
        ]
    else:
        intro = [
            "# Checkpoint Cards",
            "",
            GENERATED,
            "",
            "Every number in the results table comes from a trained model that "
            "was saved as a **checkpoint**, a file of weights. This page lists the "
            "checkpoints behind each benchmark: the parameters, the SHA-256 of the "
            "weights and the value `reproduce.py` gives from them (Reproduced). "
            "Open *Configuration and training* "
            "under a table for the architecture and the training settings. "
            "The checkpoints of the experimental GIWO are on "
            "[their own page](experimental.md).",
        ]
    lines = [
        *intro,
        "",
        "The SHA-256 is that of the weights file: the table shows its first 12 "
        "characters, and the full value is in the details and in the "
        "[checkpoint inventory](../checkpoint_inventory.csv). Code is licensed LGPL-3.0-only; the "
        "licence of the weights is on their Hugging Face repository (Download "
        "column). To reproduce the numbers, see "
        "[Reproduce our benchmarks](../reproducibility.md).",
        "",
    ]
    for s in sections:
        bench = s["bench"]
        script = SCRIPT_DIR.get(bench, bench)
        lines += [
            f"## {TITLES[bench]}",
            "",
            f"Code: `scripts/benchmarks/{script}/`. Dataset: "
            f"[dataset guide](../../dataset_guide/{GUIDE[bench]}.md).",
            "",
        ]
        if bench in UNRELEASED:
            lines += [
                "The data of this benchmark is not public, so its checkpoints are not "
                "released. The table gives the results only.",
                "",
            ]
        metrics = {(r["metric"], r["unit"]) for r in s["rows"]}
        if len(metrics) == 1:  # one metric for the whole table: say it once
            m, u = next(iter(metrics))
            lines += [f"Metric: {m} ({u}).", ""]
        lines += _table(s, hf_repo) + [""]
        if bench not in UNRELEASED:
            lines += _details(s) + [""]
    return "\n".join(lines).rstrip("\n") + "\n"


def _strip_measured(text: str) -> str:
    """Drop what depends on the reproduce run (the Reproduced column), so ``--check``
    does not need the run."""
    out, blank = [], None
    for line in text.splitlines():
        if line.startswith("| Model |"):
            heads = [h.strip() for h in line.strip().strip("|").split("|")]
            blank = [heads.index("Reproduced")]
        elif line.startswith("| ") and blank:
            cells = line.strip().strip("|").split("|")
            for i in blank:
                cells[i] = ""
            line = "|" + "|".join(cells) + "|"
        elif not line.startswith("|"):
            blank = None
        out.append(line)
    return "\n".join(out)


def build(root: Path, diff_path: Path | None) -> dict[str, str]:
    """File name -> text of the page: index.md and experimental.md."""
    diff = load_diff(diff_path)
    benches = list(dict.fromkeys(benchmark_of(c.ckpt) for c in CELLS if c.ckpt))
    order = list(TITLES)  # the problem order used across the docs
    benches.sort(key=lambda b: order.index(b) if b in order else len(order))
    hashes = weights_hashes()
    sections = [gather(b, root, diff, diff_path, hashes) for b in benches]
    experimental = [
        gather(b, root, diff, diff_path, hashes, experimental=True) for b in benches
    ]
    return {
        "index.md": render([s for s in sections if s["rows"]], HF_REPO),
        "experimental.md": render(
            [s for s in experimental if s["rows"]], HF_REPO, experimental=True
        ),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--root", type=Path, default=DEFAULT_ROOT, help="checkpoint archive"
    )
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    ap.add_argument(
        "--results", type=Path, default=None, help="results.csv from reproduce.py"
    )
    ap.add_argument(
        "--check", action="store_true", help="fail if the written cards are stale"
    )
    args = ap.parse_args(argv)
    if not args.root.is_dir():
        ap.error(f"archive {args.root} not found; set SCIREX_CKPT_ROOT or pass --root")

    cards = build(args.root, args.results)
    # pages an older version of this script wrote, one per benchmark
    old = [
        p.name
        for p in sorted(args.out_dir.glob("*.md"))
        if p.name not in cards
        and "generated by scripts/make_checkpoint_cards.py" in p.read_text()
    ]
    if args.check:
        stale = [
            n
            for n, text in cards.items()
            if not (args.out_dir / n).is_file()
            or _strip_measured((args.out_dir / n).read_text()) != _strip_measured(text)
        ]
        for n in stale + old:
            print(f"STALE: {args.out_dir / n}")
        print(f"{len(cards)} page: " + ("up to date" if not stale + old else "STALE"))
        return 1 if stale or old else 0

    args.out_dir.mkdir(parents=True, exist_ok=True)
    for n, text in cards.items():
        (args.out_dir / n).write_text(text)
    for n in old:
        (args.out_dir / n).unlink()
    print(f"wrote {len(cards)} page to {args.out_dir}, removed {len(old)} old pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
