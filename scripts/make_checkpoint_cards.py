def _json(path: Path) -> dict:
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return {}


def _fmt(d: dict) -> str:
    return ", ".join(f"{k}={json.dumps(v)}" for k, v in d.items())


def benchmark_of(ckpt: str) -> str:
    problem, regime, _ = classify(Path(ckpt))
    if problem == "darcy_s85" and regime == "physics_only":
        return "darcy_physics"  # a table of its own
    return problem


def epoch_rule(bench: str, cfg: dict, files: list[str]) -> str:
    """Which epoch's weights the file holds, as far as a file or train script says."""
    tr = cfg.get("training", {})
    if bench == "cavity":
        if "best_epoch" in tr:
            return (
                f"best validation epoch ({tr['best_epoch']} of {tr['epochs_run']} "
                "trained); train.py keeps the lowest validation loss"
            )
        return UNKNOWN
    if bench == "chip_cooling":
        return f"{UNKNOWN} (converted from an external pickle; no record of the epoch)"
    if any(f.endswith("_final.msgpack") for f in files):
        return "final epoch (file is named *_final.msgpack)"
    if "weights" in tr:
        return f"final epoch ({tr['weights']})"
    return "final epoch (train.py saves the weights after the last epoch)"


def seed_of(cfg: dict) -> str:
    tr = cfg.get("training", {})
    if "seed" not in tr:
        return UNKNOWN
    extra = f" (of seeds {tr['seeds']})" if "seeds" in tr else ""
    return f"{tr['seed']}{extra}"


def commit_of(cfg: dict, man: dict, rep: dict) -> str:
    prov = cfg.get("provenance", {})
    if prov.get("git_commit"):
        dirty = prov.get("git_dirty")
        return prov["git_commit"] + (" (uncommitted changes)" if dirty else "")
    sha = man.get("run_git_commit") or rep.get("code", {}).get("commit")
    return sha or UNKNOWN


