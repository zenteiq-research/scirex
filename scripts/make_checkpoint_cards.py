"""The Checkpoint Cards page: the checkpoints behind the results table.

    python scripts/make_checkpoint_cards.py --results reproduce_out/results.csv
    python scripts/make_checkpoint_cards.py --check     # fail if the page is stale

The page has one table per benchmark. A row is a cell of the results table: model,
checkpoint, parameters, SHA-256 and the value ``reproduce.py`` measured. Under each table, a collapsed block holds the configuration, the training
commit and the epoch rule. The text is generated from the archive (``config.json``,
``MANIFEST.json``, ``REPRODUCE.json``) and ``reproduce_paper_map.py``; edit those, not
the page. A Download column links each checkpoint to its Hugging Face repository,
``<org>/scirex-<model>-<problem>`` (``reproduce_paper_map.hf_repo_of``);
``SCIREX_HF_ORG`` changes the organisation, and an empty value leaves the column out.
Cavity has none.

A seed is taken from ``config.json`` only; a field no file records reads ``UNKNOWN``.
The weights SHA-256 is read from the checkpoint inventory
(``doc/benchmarks/checkpoint_inventory.csv``); the licence of the weights is stated on
their Hugging Face repository.
"""

