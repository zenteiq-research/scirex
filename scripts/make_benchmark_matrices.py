"""Write the benchmark matrices: one table per quantity, a row per problem, a column per model.

    python scripts/make_benchmark_matrices.py            # write the pages
    python scripts/make_benchmark_matrices.py --check    # fail if a page is stale

The pages are ``doc/benchmarks/{accuracy,compute_cost,setup}.md``. The figures of every problem are on the results summary. Every number is
read from the committed ``doc/assets/benchmarks/<problem>_<model>/metrics.json``; each cell links
to the results page of that problem and model. A cell reads "-" when ``metrics.json`` does not
hold the value. The headline of chip cooling is not in its ``metrics.json``; it is copied from
the table of ``doc/benchmarks/comparison.md`` and marked with a dagger.
"""

