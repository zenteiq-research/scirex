def dig(data: Any, *path: str | int) -> Any:
    """``data[p0][p1]...`` or None when a key is missing."""
    for key in path:
        if isinstance(data, dict) and key in data:
            data = data[key]
        elif (
            isinstance(data, list)
            and isinstance(key, int)
            and -len(data) <= key < len(data)
        ):
            data = data[key]
        else:
            return None
    return data


def number(value: Any) -> float | None:
    if isinstance(value, bool) or not isinstance(value, int | float):
        return None
    return float(value)


def first(data: Any, *paths: tuple) -> float | None:
    for path in paths:
        value = number(dig(data, *path))
        if value is not None:
            return value
    return None


def mean_of(values: Any) -> float | None:
    if (
        isinstance(values, list)
        and values
        and all(number(v) is not None for v in values)
    ):
        return sum(values) / len(values)
    return None


@dataclass(frozen=True)
class Problem:
    key: str  # folder name under doc/benchmarks
    title: str
    metric: str  # what the accuracy number is
    fmt: Callable[[float], str]
    run: Callable[[str], str | None] = lambda model: (
        None
    )  # the run inside metrics.json, if any
    directory: Callable[[str], str] = lambda model: (
        ""
    )  # folder of metrics.json under assets
    accuracy: tuple[tuple, ...] = ()
    params: tuple[tuple, ...] = ()
    epoch_s: tuple[tuple, ...] = ()
    epochs: tuple[tuple, ...] = ()
    batch: tuple[tuple, ...] = ()


def pct(digits: int) -> Callable[[float], str]:
    return lambda v: f"{v * 100:.{digits}f}%"


def plain(digits: int) -> Callable[[float], str]:
    return lambda v: f"{v:.{digits}f}"


def sci(digits: int) -> Callable[[float], str]:
    return lambda v: f"{v:.{digits}e}".replace("e-0", "e-")


