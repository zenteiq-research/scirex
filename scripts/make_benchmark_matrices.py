def load(problem: Problem, model: str, assets: Path = ASSETS) -> dict | None:
    folder = problem.directory(model) or f"{problem.key}_{model}"
    path = assets / folder / "metrics.json"
    if not path.is_file():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def value(
    problem: Problem, model: str, paths: tuple[tuple, ...], assets: Path = ASSETS
) -> float | None:
    data = load(problem, model, assets)
    if data is None:
        return None
    run = problem.run(model)
    usable = [path for path in paths if run is not None or "@" not in path]
    return first(
        data, *[tuple(run if p == "@" else p for p in path) for path in usable]
    )


def has_page(problem: Problem, model: str, doc: Path = DOC) -> bool:
    results = doc / problem.key / "results"
    assets = doc.parent / "assets" / "benchmarks" / f"{problem.key}_{model}"
    return (results / f"{model}.md").is_file() or (
        (results / "comparative.md").is_file() and assets.is_dir()
    )


def headline_table(doc: Path = DOC) -> dict[str, dict[str, str]]:
    """The cells of the headline table of ``comparison.md``: folder -> model -> text."""
    text = (doc / "comparison.md").read_text(encoding="utf-8")
    out: dict[str, dict[str, str]] = {}
    for line in text.splitlines():
        m = re.match(r"^\| \[[^\]]+\]\((\w+)/results/comparative\.md\) \|(.*)\|$", line)
        if not m:
            continue
        cells = [c.strip().strip("*") for c in m.group(2).split("|")]
        if len(cells) == len(MODELS) + 1:  # metric, then one cell per model
            out[m.group(1)] = dict(zip(MODELS, cells[1:], strict=True))
    return out


def link(text: str, problem: Problem, model: str, doc: Path = DOC) -> str:
    if text == DASH or not has_page(problem, model, doc):
        return text
    results = doc / problem.key / "results"
    page = (
        f"{model}.md"
        if (results / f"{model}.md").is_file()
        else f"comparative.md#{model}"
    )
    return f"[{text}]({problem.key}/results/{page})"


def thousands(v: float) -> str:
    return f"{int(round(v)):,}"


def seconds(v: float) -> str:
    return f"{v:.1f}" if v >= 10 else f"{v:.2f}"


def matrix(rows: list[list[str]], head: list[str]) -> str:
    out = [
        "| " + " | ".join(head) + " |",
        "| " + " | ".join(["---"] * len(head)) + " |",
    ]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def models_for(doc: Path = DOC) -> tuple[str, ...]:
    return MODELS


def build_pages(assets: Path = ASSETS, doc: Path = DOC) -> dict[str, str]:
    fallback = headline_table(doc)
    head = ["Problem", *[LABEL[m] for m in MODELS]]
    daggers = False

    def row_title(p: Problem) -> str:
        return f"**[{p.title}]({p.key}/README.md)**"

    # accuracy
    rows = []
    for p in PROBLEMS:
        cells = []
        for m in MODELS:
            v = value(p, m, p.accuracy, assets) if p.accuracy else None
            if v is not None:
                cells.append(link(p.fmt(v), p, m, doc))
            elif (
                p.key in fallback
                and fallback[p.key].get(m, DASH) != DASH
                and has_page(p, m, doc)
            ):
                cells.append(link(fallback[p.key][m] + DAGGER, p, m, doc))
                daggers = True
            else:
                cells.append(DASH)
        rows.append([row_title(p), *cells])
    metric_rows = [[f"**{p.title}**", p.metric] for p in PROBLEMS]
    acc = f"""{HEADER}
# Accuracy

The headline test error of every model on every problem. Each cell links to the section of that model on the results page of the problem. The metric differs from problem to problem (see the second table), so compare models **within a row**, not down a column. Lower is better in every row, and a dash means the model was not run on the problem.

{matrix(rows, head)}

{"The values marked " + DAGGER + " are not in the `metrics.json` of the run; they are taken from the [results summary](comparison.md)." if daggers else ""}

## What each row measures

{matrix(metric_rows, ["Problem", "Metric"])}

Each model keeps the training recipe of its own paper, so a difference reflects the architecture and its recipe together. The [results summary](comparison.md) adds the figures, and the comparison page of each problem, linked from the [overview](index.md), has the details.
"""

    # compute cost
    def cell_table(select: str, fmt: Callable[[float], str]) -> str:
        out = []
        for p in PROBLEMS:
            cells = []
            for m in MODELS:
                paths = PARAMS if select == "params" else getattr(p, select)
                v = value(p, m, paths, assets) if paths else None
                if select == "epoch_s" and p.key == "darcy":
                    t = value(p, m, (("total_time_s",),), assets)
                    n = value(p, m, (("epochs",),), assets)
                    v = t / n if t is not None and n else None
                if select == "epoch_s" and p.key == "darcy_physics":
                    t = value(p, m, (("total_time_s",),), assets)
                    n = value(p, m, (("epochs",),), assets)
                    v = t / n if t is not None and n else None
                if select == "epoch_s" and p.key == "shapenetcar":
                    t = value(p, m, (("runs", "@", "train_seconds"),), assets)
                    n = value(p, m, (("runs", "@", "n_epochs"),), assets)
                    v = t / n if t is not None and n else None
                if select == "epoch_s" and p.key == "chip_cooling":
                    d = load(p, m, assets)
                    v = mean_of(dig(d, "time")) if d else None
                cells.append(link(fmt(v), p, m, doc) if v is not None else DASH)
            out.append([row_title(p), *cells])
        return matrix(out, head)

    compute = f"""{HEADER}
# Compute cost

The size and the training cost of every model, on the GPU of the run. Each cell links to the section of that model on the results page of the problem. A dash means the value is not in the `metrics.json` of the run.

## Parameters

The number of trainable real values, with each complex spectral weight counted twice. The models of a problem are sized to about the same count.

{cell_table("params", thousands)}

## Mean time per epoch (seconds)

The wall-clock time of one training epoch: the steady-state epoch where the run records it (the first epoch includes the one-time JAX compilation), otherwise the mean over all epochs. The GPU was shared with other jobs in some runs, so treat the times as indicative, not as a controlled benchmark.

{cell_table("epoch_s", seconds)}
"""

    # setup
    def setup_cell(p: Problem, m: str) -> str:
        e = value(p, m, EPOCHS, assets)
        b = value(p, m, BATCH, assets)
        if e is None:
            return DASH
        return link(f"{int(e)} / {int(b)}" if b is not None else f"{int(e)}", p, m, doc)

    setup_rows = [[row_title(p), *[setup_cell(p, m) for m in MODELS]] for p in PROBLEMS]
    setup = f"""{HEADER}
# Setup

The training length of every model: the number of epochs and the batch size, written as `epochs / batch size`. Each cell links to the results page of the problem, which has the optimiser, the learning-rate schedule, the loss and the normalisation. A dash means the value is not in the `metrics.json` of the run.

{matrix(setup_rows, head)}
"""

    return {
        "accuracy.md": acc,
        "compute_cost.md": compute,
        "setup.md": setup,
    }


def tidy(text: str) -> str:
    return re.sub(r"\n{3,}", "\n\n", text).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if a page is stale")
    ap.add_argument("--doc", type=Path, default=DOC)
    ap.add_argument("--assets", type=Path, default=ASSETS)
    args = ap.parse_args(argv)
    pages = {n: tidy(t) for n, t in build_pages(args.assets, args.doc).items()}
    stale = []
    for name, text in pages.items():
        path = args.doc / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
    if args.check:
        for name in stale:
            print(f"STALE {name}: run python scripts/make_benchmark_matrices.py")
        print(
            f"make_benchmark_matrices: {len(pages) - len(stale)}/{len(pages)} pages up to date"
        )
        return 1 if stale else 0
    print("wrote " + ", ".join(pages))
    return 0


if __name__ == "__main__":
    sys.exit(main())
