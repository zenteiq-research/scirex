"""Check that inline code naming an API symbol or a repository file is a link.

The convention is TensorFlow's. In prose, the name of a public API symbol (a module,
class, function or ``Class.method``) is written in code font and linked to its entry in
the API reference, at every mention. A full repository path (``scripts/...``,
``src/...``) is written in code font and linked to the file on GitHub. Arguments,
command-line flags, environment variables, values and bare file names (``infer.py``,
``metrics.json``) stay plain code, never linked, because the same name exists in many
folders.

Headings, fenced code blocks, HTML comments, text that is already a link, the API pages
themselves, generated pages and files that stay private are left alone.

Usage::

    python scripts/dev/check_inline_links.py [--strict] [--fix] [FILE ...]

Without files it reads every Markdown page of the documentation, the README and
CONTRIBUTING.md. In those two, which are shown on GitHub, an API name links to the
published site. ``--fix`` writes the links. Exit status 1 with ``--strict`` when a name
is not linked.
"""

from __future__ import annotations

import argparse
import posixpath
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE_URL = "https://zenteiq-research.github.io/scirex"
# doc/dev_guide/contributing.md is generated from CONTRIBUTING.md
# (check_contributing.py --write-docs), so it is not edited here
SKIP = {"doc/dev_guide/contributing.md"}
API_DIR = "doc/api"
GENERATED = "generated by scripts/"
# modules and the API page that documents them
MODULE_PAGES = {
    f"scirex.{m}": f"api/{m}.md"
    for m in (
        "models",
        "layers",
        "losses",
        "data",
        "training",
        "config",
        "utils",
        "experimental",
    )
}
# stable sub-packages (api_policy.md): their names are documented on the parent's page
MODULE_PAGES |= {
    "scirex.layers.blocks": "api/layers.md",
    "scirex.layers.common": "api/layers.md",
    "scirex.data.containers": "api/data.md",
    "scirex.data.transforms": "api/data.md",
    "scirex.data.datasets": "api/data.md",
    "scirex.training.optim": "api/training.md",
}
DIRECTIVE = re.compile(r"^:::\s+(scirex\.[\w.]+)", re.M)
FENCE = re.compile(r"^\s*(`{3,}|~{3,})(.*)$")
SPAN = re.compile(r"(?<!`)`([^`\n]+)`(?!`)")
# something that must stay as it is: a Markdown link, an HTML tag, an autolink
KEEP = re.compile(r"(\[[^\]]*\]\([^)]*\))|(<[^>\n]+>)")
TOKEN = re.compile(r"(\[[^\]]*\]\([^)]*\))|(<[^>\n]+>)|(?<!`)`([^`\n]+)`(?!`)")
PATH = re.compile(r"^(?:scripts|src|tests|docker|\.github)/[\w./-]+$")


def api_symbols(root: Path = ROOT) -> dict[str, str]:
    """Anchor (``scirex.models.FNO``) -> API page (``api/models.md``)."""
    out: dict[str, str] = {}
    for page in sorted((root / API_DIR).glob("*.md")):
        for m in DIRECTIVE.finditer(page.read_text(encoding="utf-8")):
            out[m.group(1)] = f"api/{page.name}"
    return out


def private_paths(root: Path = ROOT) -> set[str]:
    """Files that the public copy leaves out (internal/PUBLIC_EXCLUDE.txt)."""
    f = root / "internal" / "PUBLIC_EXCLUDE.txt"
    if not f.is_file():
        return set()
    return {
        ln.strip()
        for ln in f.read_text(encoding="utf-8").splitlines()
        if ln.strip() and not ln.startswith("#")
    }


def experimental_modules(root: Path = ROOT) -> dict[str, str]:
    """The modules that the experimental page lists in its table."""
    page = root / API_DIR / "experimental.md"
    if not page.is_file():
        return {}
    cell = r"^\|\s*`(scirex\.experimental\.\w+)`\s*\|"
    names = re.findall(cell, page.read_text(encoding="utf-8"), re.M)
    return {n: "api/experimental.md" for n in names}


class Index:
    """What a code span can be linked to."""

    def __init__(self, root: Path = ROOT) -> None:
        self.root = root
        self.modules = {**MODULE_PAGES, **experimental_modules(root)}
        self.symbols = api_symbols(root)
        self.private = private_paths(root)
        self.short: dict[str, list[str]] = defaultdict(list)
        for a in self.symbols:
            self.short[a.rsplit(".", 1)[-1]].append(a)

    def api_target(self, code: str) -> str | None:
        """``page#anchor`` (relative to ``doc/``) for an API symbol, else None."""
        c = re.sub(r"\(.*\)$", "", code.strip())  # FNO(...) and name()
        if c in self.modules:
            return self.modules[c]
        if c in self.symbols:
            return f"{self.symbols[c]}#{c}"
        names = self.short.get(c, [])
        if len(names) == 1 and (c[0].isupper() or "_" in c):
            return f"{self.symbols[names[0]]}#{names[0]}"
        return None

    def path_target(self, code: str) -> str | None:
        """Repository path for a full path that exists and is published, else None."""
        c = code.strip()
        if not PATH.match(c) or c.rstrip("/") in self.private:
            return None
        if not (self.root / c).exists():
            return None
        kind = "tree" if (self.root / c).is_dir() else "blob"
        return f"{kind}/main/{c.rstrip('/')}"


def link_for(code: str, rel: str, idx: Index) -> str | None:
    """The link target for ``code`` on the page ``rel`` (a path from the repo root)."""
    if rel.startswith("doc/"):
        here = posixpath.dirname(rel[len("doc/") :])
    else:  # README.md, CONTRIBUTING.md: links are relative to the repository root
        here = None
    api = idx.api_target(code)
    if api:
        page, _, anchor = api.partition("#")
        if (
            here is None
        ):  # shown on GitHub, where the API page is raw Markdown: use the site
            return f"{SITE_URL}/{page.removesuffix('.md')}/" + (
                f"#{anchor}" if anchor else ""
            )
        return posixpath.relpath(page, here or ".") + (f"#{anchor}" if anchor else "")
    path = idx.path_target(code)
    if path:
        if here is None:
            return code.strip()
        # a relative path: the docs build turns it into a link to the repository
        return posixpath.relpath(code.strip().rstrip("/"), posixpath.join("doc", here))
    return None


def scan(text: str, rel: str, idx: Index) -> list[tuple[int, str, str, str]]:
    """Every unlinked name: (line, code, target, line text with the link written)."""
    found, fence, comment = [], None, False
    for n, line in enumerate(text.split("\n"), 1):
        m = FENCE.match(line)
        if fence is None and m:
            fence = m.group(1)
            continue
        if fence is not None:
            if (
                m
                and m.group(1)[0] == fence[0]
                and len(m.group(1)) >= len(fence)
                and not m.group(2).strip()
            ):
                fence = None
            continue
        if "<!--" in line:
            comment = True
        if comment:
            if "-->" in line:
                comment = False
            continue
        if line.lstrip().startswith("#"):
            continue

        def sub(mt: re.Match[str]) -> str:
            if mt.group(1) or mt.group(2):
                return mt.group(0)
            code = mt.group(3)
            target = link_for(code, rel, idx)
            if target is None:
                return mt.group(0)
            found.append((n, code, target, ""))
            return f"[`{code}`]({target})"

        new = TOKEN.sub(sub, line)
        if new != line:
            found[:] = [(*f[:3], new) if f[0] == n and not f[3] else f for f in found]
    return found


def fix(text: str, rel: str, idx: Index) -> str:
    lines = text.split("\n")
    for n, _code, _t, new in scan(text, rel, idx):
        lines[n - 1] = new
    return "\n".join(lines)


def pages(root: Path = ROOT) -> list[str]:
    out = subprocess.run(
        ["git", "-C", str(root), "ls-files", "doc", "README.md", "CONTRIBUTING.md"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.split()
    keep = []
    for f in out:
        if not f.endswith(".md") or f.startswith(f"{API_DIR}/") or f in SKIP:
            continue
        if f.startswith(("doc/assets/", "doc/_")):
            continue
        if GENERATED in (root / f).read_text(encoding="utf-8"):
            continue
        keep.append(f)
    return keep


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("files", nargs="*", help="pages to check (default: all)")
    ap.add_argument("--fix", action="store_true", help="write the links")
    ap.add_argument(
        "--strict", action="store_true", help="exit 1 if a name is unlinked"
    )
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)
    root = args.root.resolve()
    idx = Index(root)
    todo = args.files or pages(root)
    total = 0
    for rel in todo:
        path = root / rel
        text = path.read_text(encoding="utf-8")
        found = scan(text, rel, idx)
        if not found:
            continue
        total += len(found)
        if args.fix:
            path.write_text(fix(text, rel, idx), encoding="utf-8")
        else:
            for n, code, target, _ in found[:5]:
                print(f"{rel}:{n}: `{code}` is not linked (to {target})")
            if len(found) > 5:
                print(f"{rel}: ... and {len(found) - 5} more")
    verb = "linked" if args.fix else "unlinked"
    print(f"check_inline_links: {total} {verb} name(s) in {len(todo)} page(s)")
    return 1 if args.strict and total and not args.fix else 0


if __name__ == "__main__":
    sys.exit(main())
